const CATALOG: Record<UiLang, Partial<Record<StrKey, string>>> = { en, ar, fr, ur, id, tr, ms, bn, fa, es };

/** Right-to-left languages need reversed alignment in the terminal. */
export const isRtl = (lang: UiLang): boolean => lang === 'ar' || lang === 'ur' || lang === 'fa';

/** Translate a key for a language, falling back to English. */
export function t(key: StrKey, lang: UiLang): string {
  return CATALOG[lang]?.[key] ?? en[key];
}

